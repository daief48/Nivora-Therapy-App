export type VjKey = keyof typeof en;
const DICT = { en, bn, hi, ne } as const;
/** Self-contained lookup (own dictionaries, English fallback). Works whether or not these keys are merged into the global dictionaries. */
export function vjTranslate(lang: 'en' | 'bn' | 'hi' | 'ne', key: VjKey, vars?: Record<string, string | number>): string {
  let s: string = (DICT[lang] as Partial<Record<VjKey, string>>)[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
