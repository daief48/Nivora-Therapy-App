// Regenerates src/components/icons.ts: the subset of Ionicons names that appear as string literals in src/.
// Run after adding a new icon:  node scripts/gen-icons.js
const fs = require('fs');
const path = require('path');

const glyph = new Set(Object.keys(require('@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/Ionicons.json')));
const used = new Set();
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.tsx?$/.test(f) && f !== 'icons.ts') {
      for (const m of fs.readFileSync(p, 'utf8').matchAll(/['"]([a-z0-9-]+)['"]/g)) if (glyph.has(m[1])) used.add(m[1]);
    }
  }
})(path.join(__dirname, '..', 'src'));
// Names chosen dynamically (focused/unfocused variants, ternaries built from parts).
['home', 'home-outline', 'chatbubble-ellipses', 'chatbubble-ellipses-outline', 'book', 'book-outline', 'stats-chart', 'stats-chart-outline',
  'person', 'person-outline', 'thumbs-up', 'thumbs-up-outline', 'thumbs-down', 'thumbs-down-outline'].forEach((n) => used.add(n));

const list = [...used].sort();
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'components', 'icons.ts'),
  '/** Curated subset of Ionicons used by the app (keeps type-checking fast and catches icon typos). Generated by scripts/gen-icons.js. */\nexport type IconName =\n' +
    list.map((n) => `  | '${n}'`).join('\n') + ';\n',
);
console.log(`${list.length} icons`);
